/// Test ibig-based no-std mul_mod_n implementation
use tx_types::crypto::utils::{mul_mod_n, CHEETAH_N};

#[cfg(feature = "std")]
#[test]
fn test_ibig_mul_mod_n() {
    use num_bigint::BigUint;

    // Test with the actual challenge and secret key from our signing
    let chal_be = [
        0x1bu8, 0x6e, 0x2d, 0xba, 0xd3, 0xcb, 0xd8, 0x77, 0x9c, 0xfa, 0xb1, 0x83, 0xf0, 0xa7,
        0xea, 0xd2, 0x76, 0xe3, 0x87, 0x8e, 0xa6, 0xce, 0x47, 0xae, 0x5f, 0xba, 0xa2, 0x7d, 0xeb,
        0x8c, 0x34, 0xbb,
    ];
    let sk_be = [
        0x71u8, 0x02, 0x27, 0xad, 0x8a, 0xf1, 0x85, 0x73, 0xa5, 0x99, 0xe7, 0xdd, 0x94, 0xee,
        0xe7, 0xc1, 0xad, 0xbf, 0x10, 0xc4, 0x26, 0x1b, 0xc8, 0x8c, 0x1d, 0x5e, 0xcd, 0xa6, 0x90,
        0x92, 0x49, 0x4a,
    ];

    // Expected from BigUint
    let chal_big = BigUint::from_bytes_be(&chal_be);
    let sk_big = BigUint::from_bytes_be(&sk_be);
    let n_big = BigUint::from_bytes_be(&CHEETAH_N);
    let expected_big = (chal_big * sk_big) % n_big;
    let expected_bytes = expected_big.to_bytes_be();
    let mut expected = [0u8; 32];
    let offset = 32 - expected_bytes.len();
    expected[offset..].copy_from_slice(&expected_bytes);

    println!("Expected (BigUint): {:02x?}", expected);

    // Test the mul_mod_n function from the library
    // This will use ibig when no-std-crypto feature is enabled
    let result = mul_mod_n(&chal_be, &sk_be);

    println!("Result   (mul_mod_n): {:02x?}", result);

    if result != expected {
        println!("\n❌ MISMATCH!");
        for i in 0..32 {
            if result[i] != expected[i] {
                println!("  Byte {}: result={:02x} expected={:02x}", i, result[i], expected[i]);
            }
        }
        panic!("mul_mod_n result does not match BigUint!");
    } else {
        println!("✓ mul_mod_n matches BigUint!");
    }

    assert_eq!(result, expected);
}

