// Test no-std arithmetic with known values
// This test should work even without std

#[test]
fn test_nostd_mul_mod_n() {
    use tx_types::crypto::utils::{mul_mod_n, add_mod_n};

    // Known values
    let nonce_be = [0x70u8, 0xdd, 0xf3, 0x8c, 0xf1, 0xe7, 0x63, 0xd7, 0x91, 0xa0, 0x36, 0xab, 0xb9, 0xbe, 0x29, 0x6c, 0x28, 0x39, 0x45, 0x89, 0xac, 0x97, 0x6a, 0x1e, 0x9f, 0xbc, 0xb4, 0xbc, 0x33, 0x40, 0x71, 0x35];
    let chal_be = [0x1bu8, 0x6e, 0x2d, 0xba, 0xd3, 0xcb, 0xd8, 0x77, 0x9c, 0xfa, 0xb1, 0x83, 0xf0, 0xa7, 0xea, 0xd2, 0x76, 0xe3, 0x87, 0x8e, 0xa6, 0xce, 0x47, 0xae, 0x5f, 0xba, 0xa2, 0x7d, 0xeb, 0x8c, 0x34, 0xbb];
    let sk_be = [0x71u8, 0x02, 0x27, 0xad, 0x8a, 0xf1, 0x85, 0x73, 0xa5, 0x99, 0xe7, 0xdd, 0x94, 0xee, 0xe7, 0xc1, 0xad, 0xbf, 0x10, 0xc4, 0x26, 0x1b, 0xc8, 0x8c, 0x1d, 0x5e, 0xcd, 0xa6, 0x90, 0x92, 0x49, 0x4a];

    let expected_chal_times_sk = [0x2fu8, 0x19, 0x05, 0x84, 0x78, 0x33, 0x73, 0x89, 0x6d, 0x86, 0x40, 0x0d, 0xb6, 0x0c, 0x49, 0x5d, 0xa9, 0xa2, 0xec, 0xd4, 0x79, 0x96, 0x66, 0xb1, 0x0f, 0xbf, 0x3d, 0x72, 0x43, 0xfe, 0xf9, 0x2d];
    let expected_sig = [0x25u8, 0x04, 0x9f, 0x76, 0x2e, 0xdb, 0xb4, 0x90, 0xa8, 0xe6, 0xb7, 0xa9, 0xd6, 0xc0, 0x3b, 0x14, 0x9f, 0x61, 0x8b, 0x3a, 0xf6, 0x18, 0x59, 0xac, 0xdb, 0x38, 0x8f, 0xef, 0xc8, 0x6a, 0xbd, 0x93];

    let chal_times_sk = mul_mod_n(&chal_be, &sk_be);
    let sig = add_mod_n(&nonce_be, &chal_times_sk);

    assert_eq!(chal_times_sk, expected_chal_times_sk, "mul_mod_n mismatch");
    assert_eq!(sig, expected_sig, "signature mismatch");
}
